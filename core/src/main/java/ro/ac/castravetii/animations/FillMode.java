package ro.ac.castravetii.animations;

/**
 * Fill modes for animations. Inspired by CSS.
 * <br>
 * <b>NOTE:</b> <i>More modes to be added in a future update.</i>
 */
public enum FillMode {
    /**
     * The element remains frozen on the last keyframe.
     */
    FORWARDS,
    /**
     * No fill mode.
     */
    NONE
}
